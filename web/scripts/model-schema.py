"""Generate a small browser validation contract from the Android serializable entities."""
from pathlib import Path
import re,json
root=Path(__file__).resolve().parents[2]
classes={}
for file in (root/'app/src/main/java/com/assetboard').rglob('*.kt'):
 text=file.read_text()
 for name,body in re.findall(r'data class (\w+)\(([\s\S]*?)\n\)',text):
  fields={}
  for match in re.finditer(r'val (\w+): ([\w<>?]+)([^\n]*)',body):
   key,kind,tail=match.groups();fields[key]={'type':kind.rstrip('?'),'nullable':kind.endswith('?'),'required':'=' not in tail}
  classes[name]=fields
mapping={'groups':'AccountGroup','accounts':'Account','snapshots':'Snapshot','valuations':'Valuation','snapshotItems':'SnapshotItem','flows':'MoneyFlow','todoLists':'TodoList','todoSections':'TodoSection','todos':'Todo','checklistItems':'ChecklistItem','diaryEntries':'DiaryEntry','diaryDrafts':'DiaryDraft','habitChecks':'HabitCheck','habits':'Habit','healthProfile':'HealthProfile','bodyMeasurements':'BodyMeasurement','foodEntries':'FoodEntry','noteTopics':'NoteTopic','notes':'Note','noteSources':'NoteSource','noteDrafts':'NoteDraft','weeklyReviews':'WeeklyReview','weeklyDrafts':'WeeklyDraft','countdowns':'Countdown'}
schema={key:classes[name] for key,name in mapping.items()}
(root/'web/public/model-schema.js').write_text('// Generated by web/scripts/model-schema.py from Android entities.\nexport const modelSchema = '+json.dumps(schema,ensure_ascii=False,indent=2)+';\n')
